"""AgentBench outputs: JSON records, CSV summaries, Markdown and SVG charts.

Everything here is derived from saved ``records/*.json`` files, so reports can
be regenerated from artifacts with ``agentbridge benchmark report <dir>``.
"""

from __future__ import annotations

import csv
import json
from html import escape
from pathlib import Path
from typing import Any

from agentbridge.bench.metrics import summarize_by_configuration
from agentbridge.bench.models import ExperimentRecord

RECORD_COLUMNS = [
    "experiment_id",
    "task_id",
    "configuration",
    "repetition",
    "status",
    "status_reason",
    "test_passed",
    "hidden_tests_passed",
    "hidden_tests_failed",
    "execution_time_seconds",
    "measured_cost",
    "estimated_cost",
    "estimated_cost_source",
    "human_interventions",
    "regression_detected",
    "retries",
    "merge_success",
    "validation_outcome",
]

METRIC_ROWS = [
    ("runs_executed", "Runs executed"),
    ("runs_not_executable", "Runs not executable"),
    ("task_success_rate", "Task success rate"),
    ("test_pass_rate", "Hidden test pass rate"),
    ("mean_execution_time_seconds", "Mean execution time (s)"),
    ("median_execution_time_seconds", "Median execution time (s)"),
    ("total_measured_cost_usd", "Measured cost (USD)"),
    ("total_estimated_cost_usd", "Estimated cost (USD)"),
    ("total_input_tokens", "Input tokens"),
    ("total_output_tokens", "Output tokens"),
    ("regression_rate", "Regression rate"),
    ("retry_rate", "Retries per run"),
    ("failure_rate", "Failure rate"),
    ("human_interventions", "Human interventions"),
    ("merge_success_rate", "Merge success rate"),
]


def load_records(experiment_dir: Path) -> list[ExperimentRecord]:
    records = []
    for path in sorted((experiment_dir / "records").glob("*.json")):
        records.append(ExperimentRecord.model_validate_json(path.read_text(encoding="utf-8")))
    return records


def _cell(value: Any) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return f"{value:.4g}"
    return str(value)


def write_csv(
    records: list[ExperimentRecord], summary: dict[str, dict[str, Any]], out: Path
) -> None:
    with (out / "records.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=RECORD_COLUMNS, extrasaction="ignore")
        writer.writeheader()
        for record in records:
            writer.writerow(
                {
                    k: ("" if v is None else v)
                    for k, v in record.model_dump().items()
                    if k in RECORD_COLUMNS
                }
            )
    with (out / "summary.csv").open("w", newline="", encoding="utf-8") as handle:
        summary_writer = csv.writer(handle)
        summary_writer.writerow(["configuration", *[key for key, _ in METRIC_ROWS]])
        for name, metrics in summary.items():
            summary_writer.writerow(
                [name, *["" if metrics[k] is None else metrics[k] for k, _ in METRIC_ROWS]]
            )


def bar_chart_svg(
    title: str, values: dict[str, float | None], unit: str = "", max_value: float | None = None
) -> str:
    width, bar_h, gap, left = 640, 26, 10, 170
    height = 50 + len(values) * (bar_h + gap)
    known = [v for v in values.values() if v is not None]
    top = max_value or (max(known) if known else 1.0) or 1.0
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" font-family="sans-serif" font-size="13">',
        f'<rect width="{width}" height="{height}" fill="#ffffff"/>',
        f'<text x="12" y="24" font-size="15" font-weight="bold" fill="#222">{escape(title)}</text>',
    ]
    for index, (name, value) in enumerate(values.items()):
        y = 40 + index * (bar_h + gap)
        parts.append(f'<text x="12" y="{y + 18}" fill="#333">{escape(name)}</text>')
        if value is None:
            parts.append(f'<text x="{left}" y="{y + 18}" fill="#888">not available</text>')
            continue
        bar_w = max(1.0, (width - left - 90) * (value / top))
        parts.append(
            f'<rect x="{left}" y="{y}" width="{bar_w:.1f}" height="{bar_h}" fill="#3b6fb6"/>'
        )
        label = f"{value:.0%}" if unit == "%" else f"{value:.3g}{unit}"
        parts.append(
            f'<text x="{left + bar_w + 6:.1f}" y="{y + 18}" fill="#222">{escape(label)}</text>'
        )
    parts.append("</svg>")
    return "\n".join(parts)


def write_markdown(
    records: list[ExperimentRecord],
    summary: dict[str, dict[str, Any]],
    metadata: dict[str, Any],
    out: Path,
) -> None:
    configs = list(summary)
    lines = [
        f"# AgentBench report: {metadata.get('experiment_id', out.name)}",
        "",
        f"- Generated by AgentBridge {metadata.get('agentbridge_version')}",
        f"- Started: {metadata.get('started_at')}; finished: {metadata.get('finished_at')}",
        f"- Suite: {metadata.get('suite')}; repetitions: {metadata.get('repetitions')}",
        f"- Platform: {metadata.get('platform')}; Python {metadata.get('python')}; "
        f"{metadata.get('git')}",
        "",
        "> These numbers come only from the records in `records/`. Unavailable metrics are",
        "> shown as n/a, never as zero. Control configurations (`mock-*`) validate the",
        "> harness itself and say nothing about AI agent quality.",
        "",
        "## Summary by configuration",
        "",
        "| Metric | " + " | ".join(configs) + " |",
        "|---|" + "---|" * len(configs),
    ]
    for key, label in METRIC_ROWS:
        lines.append(f"| {label} | " + " | ".join(_cell(summary[c][key]) for c in configs) + " |")
    lines += [
        "",
        "![Task success rate](success_rate.svg)",
        "",
        "![Mean execution time](execution_time.svg)",
        "",
        "## Per-run results",
        "",
        "| Task | Configuration | Rep | Status | Hidden tests | Time (s) | Regression | "
        "Merge | Est. cost |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in records:
        tests = (
            f"{r.hidden_tests_passed}/{(r.hidden_tests_passed or 0) + (r.hidden_tests_failed or 0)}"
            if r.hidden_tests_passed is not None
            else "n/a"
        )
        status = r.status + (f" ({r.status_reason})" if r.status_reason else "")
        lines.append(
            f"| {r.task_id} | {r.configuration} | {r.repetition} | {status[:80]} | {tests} | "
            f"{_cell(r.execution_time_seconds)} | {_cell(r.regression_detected)} | "
            f"{_cell(r.merge_success)} | {_cell(r.estimated_cost)} |"
        )
    lines += [
        "",
        "## Reproducibility",
        "",
        "```json",
        json.dumps(metadata, indent=2, default=str),
        "```",
        "",
    ]
    (out / "report.md").write_text("\n".join(lines), encoding="utf-8")


def generate_reports(experiment_dir: Path) -> dict[str, dict[str, Any]]:
    records = load_records(experiment_dir)
    metadata_path = experiment_dir / "metadata.json"
    metadata = (
        json.loads(metadata_path.read_text(encoding="utf-8")) if metadata_path.exists() else {}
    )
    summary = summarize_by_configuration(records)
    (experiment_dir / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    write_csv(records, summary, experiment_dir)
    (experiment_dir / "success_rate.svg").write_text(
        bar_chart_svg(
            "Task success rate",
            {k: v["task_success_rate"] for k, v in summary.items()},
            unit="%",
            max_value=1.0,
        ),
        encoding="utf-8",
    )
    (experiment_dir / "execution_time.svg").write_text(
        bar_chart_svg(
            "Mean execution time",
            {k: v["mean_execution_time_seconds"] for k, v in summary.items()},
            unit="s",
        ),
        encoding="utf-8",
    )
    write_markdown(records, summary, metadata, experiment_dir)
    return summary
